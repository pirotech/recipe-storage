import { describe, expect, it } from "vitest";
import { normalizeForSpeech, splitSentences } from "./normalizeForSpeech";

describe("normalizeForSpeech", () => {
  it.each([
    ["Варить 15 мин.", "Варить 15 минут"],
    ["Варить 1 мин", "Варить 1 минута"],
    ["Варить 10-15 мин.", "Варить 10 или 15 минут"],
    ["Выпекать 1,5 ч.", "Выпекать 1,5 часа"],
    ["Духовку до 180 °C", "Духовку до 180 градусов Цельсия"],
    ["Нагреть до 200°С.", "Нагреть до 200 градусов Цельсия."],
    ["Добавить 2 ст. л. муки", "Добавить 2 столовые ложки муки"],
    ["Добавить 5 ч.л. соли", "Добавить 5 чайных ложек соли"],
    ["Добавить 1 ст. л. масла", "Добавить 1 столовую ложку масла"],
    [
      "Влить 200 мл молока и 1 л воды",
      "Влить 200 миллилитров молока и 1 литр воды",
    ],
    ["Взять 500 г муки", "Взять 500 граммов муки"],
    ["Жирность 20%", "Жирность 20 процентов"],
    ["Нарезать 3 шт. лука", "Нарезать 3 штуки лука"],
    // уже написано словами — не трогаем
    ["Варить 15 минут", "Варить 15 минут"],
    ["Добавить 2 лавровых листа", "Добавить 2 лавровых листа"],
    ["Взять 2 чайных ложки", "Взять 2 чайных ложки"],
  ])("%s → %s", (input, expected) => {
    expect(normalizeForSpeech(input)).toBe(expected);
  });
});

describe("splitSentences", () => {
  it("делит по предложениям, но не внутри чисел", () => {
    expect(splitSentences("Нагреть 1.5 литра. Добавить соль! Готово")).toEqual([
      "Нагреть 1.5 литра.",
      "Добавить соль!",
      "Готово",
    ]);
  });
});
