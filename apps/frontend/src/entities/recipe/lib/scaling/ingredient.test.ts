import { describe, expect, it } from "vitest";
import { canScale, parseIngredient, scaleIngredient } from "./ingredient";

const scale = (raw: string, factor: number) =>
  scaleIngredient(parseIngredient(raw), factor);

describe("scaleIngredient: форматы строк", () => {
  it.each([
    // число, единица, название
    ["2 ст.л. муки", 2, "4 ст.л. муки"],
    ["200 г муки", 1.5, "300 г муки"],
    ["1 л. воды", 3, "3 л. воды"],
    ["3 ст. ложки масла", 2, "6 ст. ложки масла"],
    ["1 ч.л. соли", 2.5, "2½ ч.л. соли"],
    // название, разделитель, количество
    ["Мясо - 1 кг", 1.5, "Мясо - 1,5 кг"],
    ["Мясо — 1 кг", 2, "Мясо — 2 кг"],
    ["Мука: 200 г", 2.5, "Мука: 500 г"],
    ["Мука, 200 г", 2, "Мука, 400 г"],
    ["Мука пшеничная 2 стакана", 1.5, "Мука пшеничная 3 стакана"],
    // количество без единицы
    ["3 яйца", 2, "6 яйца"],
    ["100 грибов", 2, "200 грибов"],
    ["2 лимона", 1.5, "3 лимона"],
    ["Лук репчатый - 1 средняя", 2, "Лук репчатый - 2 средняя"],
  ])("%s ×%s → %s", (raw, factor, expected) => {
    expect(scale(raw, factor)).toBe(expected);
  });
});

describe("scaleIngredient: числа", () => {
  it.each([
    ["1/2 стакана молока", 3, "1½ стакана молока"],
    ["1 1/2 ст. л. сахара", 2, "3 ст. л. сахара"],
    ["½ ч.л. соли", 1.5, "¾ ч.л. соли"],
    ["1½ стакана", 2, "3 стакана"],
    ["1,5 л воды", 2, "3 л воды"],
    ["0.5 л молока", 3, "1,5 л молока"],
    ["3 яйца", 0.5, "1½ яйца"],
    ["1 ст.л. масла", 0.5, "½ ст.л. масла"],
    ["1 кг картофеля", 2.5, "2,5 кг картофеля"],
    ["150 г масла", 1.5, "225 г масла"],
  ])("%s ×%s → %s", (raw, factor, expected) => {
    expect(scale(raw, factor)).toBe(expected);
  });

  it("сохраняет исходный разделитель диапазона", () => {
    expect(scale("2-3 зубчика чеснока", 2)).toBe("4-6 зубчика чеснока");
    expect(scale("200 – 250 г муки", 2)).toBe("400 – 500 г муки");
  });

  it("при множителе 1 возвращает строку без единого изменения", () => {
    expect(scale("1/2 стакана молока", 1)).toBe("1/2 стакана молока");
    expect(scale("1,5 л воды", 1)).toBe("1,5 л воды");
  });

  it("не превращает малые значения в ноль", () => {
    expect(scale("1 г соли", 0.1)).not.toMatch(/^0 /);
  });
});

describe("scaleIngredient: несколько количеств в строке", () => {
  it("пересчитывает все", () => {
    expect(scale("Яйцо - 2 шт. (около 120 г)", 1.5)).toBe(
      "Яйцо - 3 шт. (около 180 г)",
    );
    expect(scale("1 банка томатов (400 г)", 2)).toBe(
      "2 банка томатов (800 г)",
    );
    expect(scale("Вода — 1,5 л (или 6 стаканов)", 2)).toBe(
      "Вода — 3 л (или 12 стаканов)",
    );
  });
});

describe("parseIngredient: безобидные числа", () => {
  it("не принимает за количество числа внутри слов и процентов", () => {
    expect(scale("Сметана 20% - 200 г", 2)).toBe("Сметана 20% - 400 г");
    expect(scale("Мука 1 сорта - 200 г", 2)).toBe("Мука 1 сорта - 400 г");
    expect(parseIngredient("Яйца категории С1").kind).toBe("static");
    expect(parseIngredient("Омега-3").kind).toBe("static");
    expect(parseIngredient("Мука 1 сорта").kind).toBe("static");
  });

  it("единицы не путает с началом слова", () => {
    // «л» в «листья», «г» в «грибы»: это не единицы, но число в начале строки всё равно количество
    expect(scale("2 лаврушки", 2)).toBe("4 лаврушки");
    expect(scale("2 листа лавра", 2)).toBe("4 листа лавра");
  });
});

describe("parseIngredient: виды строк", () => {
  it.each([
    ["Соль по вкусу", "static"],
    ["Щепотка соли", "static"],
    ["Масло растительное для жарки", "static"],
    ["2 ст.л. муки", "scalable"],
    ["Мясо - 1 кг", "scalable"],
  ])("%s → %s", (raw, kind) => {
    expect(parseIngredient(raw).kind).toBe(kind);
  });

  it.each([
    // число осталось неразобранным: пересчёт был бы неполным
    "Тесто: 300 г муки, 2 яйца",
    // количество словами
    "Полстакана молока",
    "Пол-литра воды",
    "Две столовые ложки масла",
    "Пара зубчиков чеснока",
    // некорректная дробь
    "1/0 стакана",
  ])("%s → unknown", (raw) => {
    expect(parseIngredient(raw).kind).toBe("unknown");
  });

  it("неизвестную и статичную строки не меняет", () => {
    expect(scale("Тесто: 300 г муки, 2 яйца", 2)).toBe(
      "Тесто: 300 г муки, 2 яйца",
    );
    expect(scale("Соль по вкусу", 3)).toBe("Соль по вкусу");
  });
});

describe("canScale", () => {
  const parse = (...raws: string[]) => raws.map(parseIngredient);

  it("да, если есть что пересчитывать и нет неразобранных строк", () => {
    expect(canScale(parse("2 ст.л. муки", "Мясо - 1 кг"))).toBe(true);
  });

  it("строки без чисел не мешают", () => {
    expect(canScale(parse("200 г муки", "Соль по вкусу"))).toBe(true);
  });

  it("нет, если хотя бы одну строку разобрать не удалось", () => {
    expect(canScale(parse("200 г муки", "Полстакана молока"))).toBe(false);
  });

  it("нет, если пересчитывать нечего", () => {
    expect(canScale(parse("Соль по вкусу", "Перец по вкусу"))).toBe(false);
    expect(canScale([])).toBe(false);
  });
});
